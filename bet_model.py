def backtest_model(
    matches,
    minimum_probability=75.0,
):
    """
    Simple chronological backtest.

    The model only uses matches BEFORE the match
    being tested.

    This helps avoid future-data leakage.
    """

    print()
    print("=" * 60)
    print("📊 BET MODEL BACKTEST")
    print("=" * 60)

    if not matches:
        print("❌ No matches.")
        return

    # Sort chronologically
    sorted_matches = sorted(
        matches,
        key=lambda x: (
            getattr(x, "date", "") or ""
        )
    )

    total_predictions = 0
    qualified_predictions = 0
    correct_predictions = 0

    results = []

    # Start after enough historical matches
    for index in range(
        MIN_MATCHES_REQUIRED,
        len(sorted_matches),
    ):

        current = sorted_matches[index]

        # Only data BEFORE current match
        historical = sorted_matches[:index]

        prediction = predict_match(
            home_team=current.home_team,
            away_team=current.away_team,
            historical_matches=historical,
        )

        if prediction is None:
            continue

        total_predictions += 1

        if not qualifies_for_accumulator(
            prediction,
            minimum_probability,
        ):
            continue

        qualified_predictions += 1

        # ----------------------------------------------------
        # Determine model prediction
        # ----------------------------------------------------

        pick = prediction.best_selection

        actual_home = current.home_goals
        actual_away = current.away_goals

        if pick == "1X":

            correct = (
                actual_home >= actual_away
            )

        elif pick == "X2":

            correct = (
                actual_away >= actual_home
            )

        elif pick == "Over 1.5":

            correct = (
                actual_home +
                actual_away
                >= 2
            )

        elif pick == "BTTS Yes":

            correct = (
                actual_home >= 1
                and
                actual_away >= 1
            )

        else:

            correct = False

        if correct:
            correct_predictions += 1

        results.append({
            "home": current.home_team,
            "away": current.away_team,
            "pick": pick,
            "probability": (
                prediction.best_probability
            ),
            "actual": (
                f"{actual_home}-{actual_away}"
            ),
            "correct": correct,
        })

    # ========================================================
    # RESULTS
    # ========================================================

    print()

    print(
        f"📌 Model predictions: "
        f"{total_predictions}"
    )

    print(
        f"🎯 Qualified ≥ "
        f"{minimum_probability}%: "
        f"{qualified_predictions}"
    )

    print(
        f"✅ Correct: "
        f"{correct_predictions}"
    )

    if qualified_predictions > 0:

        hit_rate = (
            correct_predictions /
            qualified_predictions
        ) * 100

        print()
        print(
            f"📈 Historical Hit Rate: "
            f"{hit_rate:.2f}%"
        )

    else:

        hit_rate = 0.0

        print()
        print(
            "⚠️ No qualified predictions."
        )

    print()
    print("=" * 60)

    # ========================================================
    # LAST 10 QUALIFIED PREDICTIONS
    # ========================================================

    print(
        "LAST QUALIFIED PREDICTIONS"
    )

    print("=" * 60)

    for item in results[-10:]:

        status = (
            "✅"
            if item["correct"]
            else "❌"
        )

        print(
            f"{status} "
            f"{item['home']} vs "
            f"{item['away']}"
        )

        print(
            f"   Pick: {item['pick']}"
        )

        print(
            f"   Model: "
            f"{item['probability']:.1f}%"
        )

        print(
            f"   Result: "
            f"{item['actual']}"
        )

        print()

    return {
        "total_predictions":
            total_predictions,

        "qualified_predictions":
            qualified_predictions,

        "correct_predictions":
            correct_predictions,

        "hit_rate":
            round(hit_rate, 2),
    }


