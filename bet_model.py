# ============================================================
# FIND ACCUMULATOR CANDIDATES
# ============================================================

def find_accumulator_candidates(
    predictions: list[MatchPrediction],
    minimum_probability: float = MIN_MODEL_PROBABILITY,
) -> list[MatchPrediction]:
    """
    Return only predictions that pass
    the model probability threshold.
    """

    candidates = []

    for prediction in predictions:

        if qualifies_for_accumulator(
            prediction,
            minimum_probability,
        ):
            candidates.append(prediction)

    # Highest probability first
    candidates.sort(
        key=lambda x: x.best_probability or 0,
        reverse=True,
    )

    return candidates


